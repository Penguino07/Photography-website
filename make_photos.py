#!/usr/bin/env python3
"""
Builds photos.js from a folder of images.

FILE NAME FORMAT:  Category - Title.jpg
  "Sports - Fourth Quarter.jpg"  ->  category "Sports", title "Fourth Quarter"
  A file without " - " is put in the category "Uncategorized".

YEAR:   read from the photo's date taken (EXIF metadata). If the photo has
        none (for example, an exported edit), the file's modified date is used.
RATIO:  "4 / 5" for portrait photos, "3 / 2" for landscape photos.

Each photo is copied into the site's photos/ folder so the website can load it
(browsers can't read files from anywhere on your computer).

USAGE (run once, and again whenever you add or rename photos):
  pip install pillow
  python make_photos.py "/Users/you/Desktop/My Photos"
  python make_photos.py "C:\\Users\\you\\Desktop\\My Photos"
"""

import datetime
import json
import shutil
import sys
from pathlib import Path
from urllib.parse import quote
from math import gcd

from PIL import Image, ImageOps

SITE_DIR = Path(__file__).resolve().parent
PHOTO_FOLDER = "photos"
IMAGE_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff"}
SEPARATOR = " - "

EXIF_IFD = 0x8769          # where camera date tags live
DATE_TIME_ORIGINAL = 36867 # date the photo was taken
DATE_TIME = 306            # general date tag, used as a backup


def read_year(path: Path, img: Image.Image) -> int:
    try:
        exif = img.getexif()
        camera = exif.get_ifd(EXIF_IFD)
        raw = camera.get(DATE_TIME_ORIGINAL) or exif.get(DATE_TIME)
        if raw:
            return int(str(raw)[:4])
    except Exception:
        pass
    return datetime.datetime.fromtimestamp(path.stat().st_mtime).year


def read_category_and_title(stem: str):
    if SEPARATOR in stem:
        category, title = stem.split(SEPARATOR, 1)
        return category.strip(), title.strip()
    return "Uncategorized", stem.strip()

def aspect_ratio(width, height):
    d = gcd(width, height)
    return f"{width // d} / {height // d}"

def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    source = Path(sys.argv[1]).expanduser()
    if not source.is_dir():
        print(f"Folder not found: {source}")
        sys.exit(1)

    out_dir = SITE_DIR / PHOTO_FOLDER
    out_dir.mkdir(exist_ok=True)

    photos = []
    for file in sorted(source.iterdir()):
        if not file.is_file() or file.suffix.lower() not in IMAGE_TYPES:
            continue

        category, title = read_category_and_title(file.stem)

        with Image.open(file) as img:
            img = ImageOps.exif_transpose(img)
            width, height = img.size
            print(title)
            print(img.size)
            print(str(width) + ":" + str(height) + "\n")
            year = read_year(file, img)
            ratio = aspect_ratio(width, height)

        shutil.copy2(file, out_dir / file.name)

        photos.append({
            "title": title,
            "category": category,
            "year": str(year),
            "ratio": ratio,
            "src": f"{PHOTO_FOLDER}/{quote(file.name)}",
        })

    # Newest first, then alphabetical by title.
    photos.sort(key=lambda p: (-int(p["year"]), p["title"]))

    lines = [
        "// Generated by make_photos.py. Re-run the script to update this list.",
        "const PHOTOS = [",
    ]
    for p in photos:
        lines.append(
            "  { title: %s, category: %s, year: %s, ratio: %s, src: %s },"
            % (json.dumps(p["title"]), json.dumps(p["category"]), json.dumps(p["year"]),
               json.dumps(p["ratio"]), json.dumps(p["src"]))
        )
    if photos:
        lines[-1] = lines[-1].rstrip(",")
    lines.append("];")
    lines.append("export { PHOTOS };")
    (SITE_DIR / "photos.js").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Done. {len(photos)} photos written to photos.js and copied to {PHOTO_FOLDER}/")
    


if __name__ == "__main__":
    main()
